def render(name: str, palette: dict, rows: str):
    lines = [r for r in rows.strip("\n").split("\n")]
    assert len(lines) == 16, (name, len(lines))
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, line in enumerate(lines):
        assert len(line) == 16, (name, y, len(line))
        for x, ch in enumerate(line):
            if ch == ".":
                continue
            col = K if ch == "k" else palette[ch]
            img.putpixel((x, y), tuple(int(col[i:i + 2], 16) for i in (1, 3, 5)) + (255,))
    return img.resize((16 * SCALE, 16 * SCALE), Image.NEAREST)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (palette, rows) in ART.items():
        render(name, palette, rows).save(OUT / f"{name}.png", optimize=True)
        print("item", name)


if __name__ == "__main__":
    main()
